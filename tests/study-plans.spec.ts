import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'
import { expectCurrent, navTo } from './nav'

const ID = 'applied-ai-ml-10wk'
const TITLE = '10-week Applied AI / ML engineer plan'
const KEY = 'devprep.plans.v1'
const MOD = process.platform === 'darwin' ? 'Meta' : 'Control'
const h1 = (page: Page) => page.getByRole('heading', { level: 1 })
const stored = (page: Page) => page.evaluate(([key, id]) => JSON.parse(localStorage.getItem(key) ?? '{}')[id], [KEY, ID])
const fits = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
const axe = async (page: Page) => (await new AxeBuilder({ page }).exclude('.cm-scroller').analyze()).violations.map(violation => ({ id: violation.id, targets: violation.nodes.map(node => node.target.join(' ')) }))

async function startPlan(page: Page) {
  await page.goto(`./#plans/${ID}`)
  await expect(h1(page)).toHaveText(TITLE)
  await page.getByRole('button', { name: 'Start today' }).click()
  await expect(page.getByRole('heading', { level: 2, name: 'Today' })).toBeVisible()
}

test('the list links to the plan, which shows its setup, rhythm and three phases', async ({ page }) => {
  await page.goto('./#plans')
  await expect(h1(page)).toHaveText('Study plans')
  await expect(h1(page)).toBeFocused()
  await expect(page.getByRole('link', { name: 'Build your own plan' })).toHaveAttribute('href', '#plan')
  await page.getByRole('link', { name: TITLE }).click()
  await expect(page).toHaveURL(new RegExp(`#plans/${ID}$`))
  await expect(h1(page)).toHaveText(TITLE)
  await expect(h1(page)).toBeFocused()
  await expect(page.getByRole('heading', { level: 2, name: 'Weekly rhythm' })).toBeVisible()
  await expect(page.getByRole('heading', { level: 2, name: /^Phase \d:/ })).toHaveCount(3)
  await expect(page.locator('details.plans-week, .plans-phase details')).toHaveCount(10)
  await expect(page.getByLabel('Interview language')).toHaveValue('python')
})

test('an unknown plan id is a missing page, and the Plan page links to study plans', async ({ page }) => {
  await page.goto('./#plans/no-such-plan')
  await expect(h1(page)).toHaveText('This page isn’t on the roadmap.')
  await page.goto('./#plan')
  await page.getByRole('link', { name: 'Follow a structured study plan' }).click()
  await expect(h1(page)).toHaveText('Study plans')
})

test('starting the plan, ticking items and choosing a track persist across reloads', async ({ page }) => {
  await startPlan(page)
  const item = page.locator('#item-w1-d1-1')
  await item.check()
  await expect(page.locator('#today-w1-d1-1')).toBeChecked()
  await expect(page.getByText('1 of', { exact: false }).first()).toBeVisible()
  await page.getByRole('radio', { name: /^ML engineer/ }).check()
  await expect(page.getByText('Week 8: ML fundamentals and metrics')).toBeVisible()
  await expect(page.getByText('Week 8: Retrieval, prompts and agents')).toHaveCount(0)
  await page.getByRole('radio', { name: 'Passed' }).first().check()
  await expect.poll(async () => (await stored(page))?.track).toBe('ml-engineer')
  await page.reload()
  await expect(h1(page)).toHaveText(TITLE)
  await expect(page.locator('#item-w1-d1-1')).toBeChecked()
  await expect(page.getByRole('radio', { name: /^ML engineer/ })).toBeChecked()
  await expect(page.getByRole('radio', { name: 'Passed' }).first()).toBeChecked()
  await page.getByRole('radio', { name: /^Applied AI/ }).check()
  await expect(page.getByText('Week 8: Retrieval, prompts and agents')).toBeVisible()
  await page.locator('#item-w1-d1-1').uncheck()
  await expect.poll(async () => (await stored(page))?.done ?? {}).toEqual({})
})

test('the error log adds, edits and deletes entries', async ({ page }) => {
  await startPlan(page)
  const form = page.getByRole('form', { name: 'Add error-log entry' })
  await form.getByLabel('Problem (required)').fill('Merge overlapping ranges')
  await form.getByLabel('Pattern it needed').fill('Sort, then sweep')
  await form.getByLabel('Why I missed it').fill('Did not sort first')
  await form.getByRole('button', { name: 'Add entry' }).click()
  const log = page.locator('.plans-section').filter({ has: page.getByRole('heading', { name: 'Error log' }) })
  await expect(log.getByRole('heading', { level: 3, name: 'Merge overlapping ranges' })).toBeVisible()
  await log.getByRole('button', { name: 'Edit: Merge overlapping ranges' }).click()
  const editing = page.getByRole('form', { name: 'Edit error-log entry' })
  await editing.getByLabel('Problem (required)').fill('Merge ranges')
  await editing.getByRole('button', { name: 'Save entry' }).click()
  await expect(log.getByRole('heading', { level: 3, name: 'Merge ranges' })).toBeVisible()
  await page.reload()
  await expect(log.getByRole('heading', { level: 3, name: 'Merge ranges' })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await log.getByRole('button', { name: 'Delete: Merge ranges' }).click()
  await expect(log.getByText('No entries yet.')).toBeVisible()
  expect((await stored(page)).errors).toEqual([])
})

test('scorecards add, edit and delete', async ({ page }) => {
  await startPlan(page)
  const form = page.getByRole('form', { name: 'Add scorecard' })
  await form.getByRole('radio', { name: 'System design' }).check()
  await form.getByLabel('Mock (required)').fill('Document Q&A mock')
  await form.getByLabel('Notes').fill('Spend longer on evaluation.')
  await form.getByRole('button', { name: 'Add scorecard' }).click()
  const scores = page.locator('.plans-section').filter({ has: page.getByRole('heading', { name: 'Mock scorecards' }) })
  await expect(scores.getByRole('heading', { level: 3, name: /^Document Q&A mock/ })).toContainText('System design')
  await scores.getByRole('button', { name: 'Edit: Document Q&A mock' }).click()
  const editing = page.getByRole('form', { name: 'Edit scorecard' })
  await editing.getByLabel('Mock (required)').fill('Doc Q&A mock 2')
  await editing.getByRole('button', { name: 'Save scorecard' }).click()
  await expect(scores.getByRole('heading', { level: 3, name: /^Doc Q&A mock 2/ })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await scores.getByRole('button', { name: 'Delete: Doc Q&A mock 2' }).click()
  await expect(scores.getByText('No scorecards yet.')).toBeVisible()
  expect((await stored(page)).scores).toEqual([])
})

test('Home shows today in a started plan and links back to it', async ({ page }) => {
  await page.goto('./#home')
  await expect(h1(page)).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Today in your plan' })).toHaveCount(0)
  await startPlan(page)
  await page.goto('./#home')
  const card = page.getByRole('region', { name: 'Today in your plan' })
  await expect(card).toContainText('Week 1, day 1')
  await expect(card).toContainText('Count pair sums')
  await card.getByRole('link', { name: `Open ${TITLE}` }).click()
  await expect(h1(page)).toHaveText(TITLE)
})

test('the nav, site map and palette all reach study plans', async ({ page }) => {
  await page.goto('./#home')
  await expect(h1(page)).toBeVisible()
  await navTo(page, 'Study plans')
  await expect(page).toHaveURL(/#plans$/)
  await expect(h1(page)).toHaveText('Study plans')
  await expectCurrent(page, 'Study plans')
  await page.goto('./#map')
  await expect(h1(page)).toBeVisible()
  await expect(page.getByRole('main').getByRole('link', { name: /^Study plans/ }).first()).toHaveAttribute('href', '#plans')
  await expect(page.getByRole('main').locator(`a[href="#plans/${ID}"]`).first()).toBeAttached()
  await page.keyboard.press(`${MOD}+k`)
  const dialog = page.getByRole('dialog', { name: 'Search DevPREP' })
  await dialog.getByRole('combobox').fill('Applied AI ML engineer plan')
  await expect(dialog.getByRole('option').first()).toContainText(TITLE)
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(new RegExp(`#plans/${ID}$`))
  await expect(h1(page)).toHaveText(TITLE)
})

for (const width of [360, 768, 1440]) {
  for (const theme of ['light', 'dark'] as const) {
    test(`study plans are accessible and fit at ${width}px in ${theme}`, async ({ page }) => {
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.setViewportSize({ width, height: 900 })
      await page.goto('./#plans')
      await expect(h1(page)).toHaveText('Study plans')
      expect(await axe(page), `list at ${width} ${theme}`).toEqual([])
      expect(await fits(page)).toBe(true)
      await startPlan(page)
      await page.locator('#item-w1-d1-1').check()
      await page.getByRole('form', { name: 'Add error-log entry' }).getByLabel('Problem (required)').fill('A long problem name that should wrap neatly on small screens')
      await page.getByRole('button', { name: 'Add entry' }).click()
      await page.locator('.plans-phase details').last().locator('summary').click()
      await page.waitForTimeout(300)
      expect(await axe(page), `plan at ${width} ${theme}`).toEqual([])
      expect(await fits(page)).toBe(true)
      await page.goto('./#home')
      await expect(page.getByRole('region', { name: 'Today in your plan' })).toBeVisible()
      expect(await axe(page), `home at ${width} ${theme}`).toEqual([])
      expect(await fits(page)).toBe(true)
    })
  }
}
